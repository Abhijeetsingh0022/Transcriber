prompt = f"""You are an expert Hindi linguistic editor and ASR transcript post-processor.
The following transcript was generated by Speech-to-Text (Whisper), which caused phonetic errors, Perso-Arabic/Urdu character bleeds (like 'ل', 'ت', 'ہے'), and misspelled Hinglish technical terms.

Fix each line so it is written in clean, correct, natural Hindi (Devanagari script) with standard technical terms (like आईसी, सर्किट, इनपुट, आउटपुट, पार्ट्स, कैलकुलेटर).
Strict Rules:
1. Fix corrupted characters (remove any Urdu/Arabic letters like 'ل', 'ت', 'ہے' and use proper Hindi like 'मिलता', 'मांगता', 'है').
2. Fix phonetic mishearings (e.g. 'कड़ता' -> 'करता', 'लैकि' -> 'लेकिन', 'काभी' -> 'कभी', 'इस्टमाल/इश्टमाल' -> 'इस्तेमाल', 'डंपुट' -> 'इनपुट', 'ऑटपड' -> 'आउटपुट', 'कहेटे हूँ' -> 'कहते हैं', 'हो था का ही' -> 'होता क्या है').
3. Keep the exact meaning, speaker intent, and word count/structure aligned with the original speech.
4. Return ONLY valid JSON with this exact schema:
{{
  "corrections": [
    {{"index": 0, "corrected_text": "..."}}
  ]
}}

Input lines:
{json.dumps(test_samples, ensure_ascii=False, indent=2)}
"""

res, prov = call_ai_json(prompt, task_tag="hindi_cleanup", timeout=25.0)
print("Provider:", prov)
for item in res.get("corrections", []):
    print(f"[{item['index']}] BEFORE: {test_samples[item['index']]['text']}")
    print(f"[{item['index']}] AFTER:  {item['corrected_text']}")
    print("-" * 50)
