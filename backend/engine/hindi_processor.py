"""
Hindi & Multilingual Linguistic Processor and ASR Script Normalizer.
Provides:
1. Fast rule-based Unicode sanitizer for Perso-Arabic / Urdu character bleed in Devanagari text.
2. AI-driven phonetic and technical term refiner (using Gemini / OpenRouter API keys).
3. Database persistence for cleaned transcript segments.
"""

import re
import json
import sqlite3
from typing import List, Dict, Any, Optional

from engine.ai_client import call_ai_json

# Common Perso-Arabic character replacements when accidentally emitted by Whisper in Devanagari words
PERSO_ARABIC_MAP = {
    "\u0644": "ल",  # Arabic Lam (ل)
    "\u062A": "त",  # Arabic Teh (ت)
    "\u0679": "ट",  # Urdu Tteh (ٹ)
    "\u06C2": "है", # Urdu Heh Goal with Hamza Above (ہے)
    "\u06C1": "ह",  # Urdu Heh Goal (ہ)
    "\u06CC": "ी",  # Urdu Farsi Yeh (ی)
    "\u062F": "द",  # Arabic Dal (د)
    "\u0631": "र",  # Arabic Reh (ر)
    "\u0646": "न",  # Arabic Noon (ن)
    "\u06A9": "क",  # Urdu Keheh (ک)
    "\u06AF": "ग",  # Urdu Gaf (گ)
    "\u0645": "म",  # Arabic Meem (م)
    "\u0633": "स",  # Arabic Seen (س)
    "\u0628": "ब",  # Arabic Beh (ب)
    "\u067E": "प",  # Urdu Peh (پ)
    "\u0686": "च",  # Urdu Tcheh (چ)
    "\u062C": "ज",  # Arabic Jeem (ج)
}

from concurrent.futures import ThreadPoolExecutor, as_completed

# Pre-compiled translation table for instant C-speed character translation
_PERSO_ARABIC_TRANS_TABLE = str.maketrans(PERSO_ARABIC_MAP)
_STRAY_ARABIC_REGEX = re.compile(r"[\u0600-\u06FF]")
_DOUBLE_SPACE_REGEX = re.compile(r"\s+")

HINDI_LEXICAL_PROMPT = (
    "यह एक हिंदी वार्तालाप वीडियो है। नमस्ते, मैं, आप, करते हैं, क्या, लेकिन, "
    "इस्तेमाल, कॉम्पोनेंट्स, आईसी (IC), सर्किट, इनपुट, आउटपुट, एलईडी, पिन।"
)


def clean_perso_arabic_bleed(text: str) -> str:
    """
    Strips or replaces stray Perso-Arabic / Urdu glyphs that Whisper accidentally
    interleaves into Devanagari words due to shared Hindustani acoustic tokens.
    Uses C-level str.translate for maximum performance.
    """
    if not text:
        return ""

    # Fast path: skip if string contains zero Perso-Arabic code points
    if not _STRAY_ARABIC_REGEX.search(text):
        return text

    # Translate mapped glyphs and strip remaining diacritics
    translated = text.translate(_PERSO_ARABIC_TRANS_TABLE)
    cleaned = _STRAY_ARABIC_REGEX.sub("", translated)
    return _DOUBLE_SPACE_REGEX.sub(" ", cleaned).strip()


def polish_segments_with_ai(
    segments: List[Dict[str, Any]],
    batch_size: int = 40,
    timeout: float = 30.0,
    max_workers: int = 3,
) -> Dict[int, str]:
    """
    Polishes ASR transcript lines using the configured AI gateway (Gemini / OpenRouter):
    - Corrects phonetic mishearings and dialect drift into natural Devanagari Hindi
    - Normalizes Indian-accented technical loanwords
    - Preserves exact conversational meaning, timing, and word flow
    - Uses concurrent batch execution for minimum latency
    """
    corrections: Dict[int, str] = {}
    if not segments:
        return corrections

    # Pre-clean stray Perso-Arabic glyphs locally first
    pre_cleaned_lines = []
    for idx, seg in enumerate(segments):
        txt = clean_perso_arabic_bleed(seg.get("text", "").strip())
        pre_cleaned_lines.append({"index": idx, "text": txt})

    batches = [
        pre_cleaned_lines[i : i + batch_size]
        for i in range(0, len(pre_cleaned_lines), batch_size)
    ]

    def _process_batch(batch: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
        prompt = (
            "You are an expert Hindi linguistic editor and ASR transcript post-processor.\n"
            "The following transcript was generated by Whisper Speech-to-Text on a Hindi recording.\n"
            "Whisper produced phonetic mishearings, dialect drift, and misspelled technical loanwords.\n\n"
            "Fix each line so it is written in clean, correct, natural Hindi (Devanagari script) with standard technical vocabulary.\n"
            "Strict Rules:\n"
            "1. Fix phonetic mishearings and colloquial dialect drift into standard grammatical Devanagari Hindi.\n"
            "2. Transliterate technical and English loanwords into standard Devanagari (e.g. आईसी, सर्किट, इनपुट, आउटपुट, पार्ट्स, कैलकुलेटर, कंपोनेंट्स).\n"
            "3. Retain all real participant names, vocatives, and honorific titles exactly as spoken.\n"
            "4. Keep the exact conversational meaning and tone aligned with spoken dialogue.\n"
            "5. Return ONLY valid JSON with this exact schema:\n"
            "{\n"
            '  "corrections": [\n'
            '    {"index": 0, "corrected_text": "..."}\n'
            "  ]\n"
            "}\n\n"
            "Input lines:\n"
            f"{json.dumps(batch, ensure_ascii=False, indent=2)}"
        )
        try:
            res, _ = call_ai_json(prompt, task_tag="hindi_cleanup", timeout=timeout)
            if res and isinstance(res, dict):
                return res.get("corrections", [])
        except Exception:
            pass
        return []

    def _record_item(item: Dict[str, Any]):
        raw_idx = item.get("index")
        corr = item.get("corrected_text", "").strip()
        if raw_idx is not None and corr:
            try:
                corrections[int(raw_idx)] = corr
            except (ValueError, TypeError):
                pass

    if len(batches) == 1:
        for item in _process_batch(batches[0]):
            _record_item(item)
    else:
        with ThreadPoolExecutor(max_workers=min(max_workers, len(batches))) as executor:
            future_to_batch = {executor.submit(_process_batch, b): b for b in batches}
            for future in as_completed(future_to_batch):
                try:
                    for item in future.result():
                        _record_item(item)
                except Exception:
                    pass

    # For any lines not returned by AI, fallback to the pre-cleaned local text
    for item in pre_cleaned_lines:
        idx = item["index"]
        if idx not in corrections:
            corrections[idx] = item["text"]

    return corrections


def polish_and_save_job_transcript(
    db_path: Optional[str] = None,
    job_id: str = "",
) -> Dict[str, Any]:
    """
    Cleans and polishes transcript segments for a job and persists
    the updated text to segments, words, and transcripts tables.
    Reuses centralized get_db() session manager and sync_segment_words.
    """
    from db.database import get_db
    from db.crud import sync_segment_words, is_safe_id

    if not is_safe_id(job_id):
        return {"error": "Invalid job ID"}

    with get_db() as conn:
        cursor = conn.cursor()

        cursor.execute(
            """
            SELECT id, segment_index, start_time, end_time, speaker_label, text 
            FROM segments 
            WHERE job_id = ? 
            ORDER BY segment_index ASC
            """,
            (job_id,)
        )
        rows = cursor.fetchall()
        if not rows:
            return {"error": "No segments found for job"}

        segments = [dict(r) for r in rows]
        corrections = polish_segments_with_ai(segments)

        # Batch update segments and synchronize word records
        updates = []
        new_full_text_parts = []
        total_word_count = 0
        for idx, seg in enumerate(segments):
            new_text = corrections.get(idx, seg["text"])
            updates.append((new_text, seg["id"]))
            new_full_text_parts.append(new_text)
            total_word_count += len(new_text.split())

            # Synchronize words table for this segment
            sync_segment_words(
                conn,
                seg["id"],
                new_text,
                start_time=seg["start_time"],
                end_time=seg["end_time"],
                job_id=job_id,
                speaker_label=seg.get("speaker_label"),
            )

        cursor.executemany("UPDATE segments SET text = ? WHERE id = ?", updates)

        # Update parent transcript record
        full_text = " ".join(new_full_text_parts)
        cursor.execute(
            """
            UPDATE transcripts 
            SET full_text = ?, word_count = ?, updated_at = CURRENT_TIMESTAMP 
            WHERE job_id = ?
            """,
            (full_text, total_word_count, job_id)
        )

        return {
            "success": True,
            "job_id": job_id,
            "updated_segments": len(updates),
            "word_count": total_word_count,
            "full_text": full_text[:200] + "...",
        }

